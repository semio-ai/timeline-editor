import { useCallback, useState, type KeyboardEvent } from "react";

export interface EditableLabelControls {
  /** Value to bind to the input: the local draft while editing, else committed. */
  value: string;
  /** True while an unsaved local edit is in progress. */
  editing: boolean;
  onChange: (next: string) => void;
  onBlur: () => void;
  onKeyDown: (event: KeyboardEvent<HTMLInputElement>) => void;
}

/**
 * Decouples an editable name field from its committed (often derived) value.
 *
 * Several row labels — track, group, entity, animation-instance — display a
 * value that a store subscription recomputes one render AFTER the write lands.
 * For example, group rows write `track.groupName` via `updateTrackGroupName`
 * but display `sourceRow.name`, which is regenerated by the view-filtered
 * source-rows subscription. Binding a controlled `<input>` straight to that
 * derived value drops a keystroke on every edit: the input resets to the
 * pre-write string before the subscription catches up, so the next character
 * overwrites the last (e.g. "Quori" + "X" → "Quorx"). Keeping a local draft
 * while focused and committing on blur / Enter removes the round-trip entirely.
 *
 * Empty or whitespace-only drafts, and no-op edits, are never committed.
 */
export function useEditableLabel(
  committed: string,
  onCommit: (value: string) => void,
): EditableLabelControls {
  const [draft, setDraft] = useState<string | null>(null);

  const onChange = useCallback((next: string) => {
    setDraft(next);
  }, []);

  const commit = useCallback(() => {
    setDraft((current) => {
      if (current !== null && current.trim() && current !== committed) {
        onCommit(current);
      }
      // Drop the draft so the field re-syncs to the committed value.
      return null;
    });
  }, [committed, onCommit]);

  const onKeyDown = useCallback(
    (event: KeyboardEvent<HTMLInputElement>) => {
      if (event.key === "Enter") {
        commit();
        event.currentTarget.blur();
      }
    },
    [commit],
  );

  return {
    value: draft ?? committed,
    editing: draft !== null,
    onChange,
    onBlur: commit,
    onKeyDown,
  };
}
